<h2>
 Žlutý čaj
</h2>
<p>
 Žlutý čaj je vzácná čínská specialita, která se svou chutí i vzhledem nachází někde mezi čajem zeleným a bílým. Dříve byl tento druh čaje vyhrazen pouze pro císařský dvůr a jeho výroba byla přísně střeženým tajemstvím. Dnes je vyhledáván pro svou nasládlou, medovou chuť a absenci "trávových" tónů, které jsou typické pro čaje zelené.
</p>  <img src="img/zluty1.jpg" alt="Jun Shan Yin Zhen - Stříbrné jehly z hory Jun, jeden z nejslavnějších žlutých čajů" title="Jun Shan Yin Zhen - Stříbrné jehly z hory Jun" height="165" width="220" class="vpravo">
     
<p>
 Stejně jako ostatní druhy, i žlutý čaj pochází z rostliny Camellia sinensis. Sklízejí se zpravidla jen ty nejmladší a nejkvalitnější pupeny. Specifická žlutá barva nálevu i samotných lístků není dána stářím, ale unikátním procesem zpracování, který odstraňuje svíravost a dodává čaji jeho charakteristickou jemnost.
</p>
<h2>
 Výroba a "Men Huan"
</h2>
<p>
 Proces výroby žlutého čaje je velmi pracný a vyžaduje mistrovskou zručnost. <img src="img/zluty2.jpg" alt="Tradiční příprava žlutého čaje v provincii Hunan" title="Tradiční příprava žlutého čaje" height="171" width="220" class="vlevo"> Podobně jako u zeleného čaje se lístky zahřejí, aby se zastavila oxidace. Hlavní rozdíl však spočívá v následné fázi zvané "Men Huan" (dušení pod pokličkou nebo v látce).
</p> 
<p>
 Během této fáze se ještě teplé a vlhké lístky zabalí do speciálního papíru nebo látky a nechají se několik hodin až dní odpočívat. Díky zbytkovému teplu a vlhkosti lístky mírně zežloutnou a dojde k částečné fermentaci, která rozvine typické aroma. Tento proces se často několikrát opakuje, než je čaj finálně dosušen.
</p>